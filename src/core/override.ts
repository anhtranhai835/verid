import { isOverridable, type ErrorCode, type MessageKey, type RuleCode } from "./errors.js";
import type { DeniedAction, State } from "./state.js";

/**
 * Two-step override, typed by the developer:
 *   /verid tip <reason>  → block the prompt, show a risk warning + one-time code to the dev only
 *   /verid confirm <code>  → create one override bound to the last denied action
 * `/verid peek` and `/verid menu` show the developer where things stand. Each is also
 * `/verid:<name>`, as picked from Claude Code's menu.
 */
export type PromptCommand =
  | { kind: "none" }
  | { kind: "usage" }
  | { kind: "tip"; reason: string }
  | { kind: "confirm"; code: string }
  | { kind: "peek" }
  | { kind: "menu" };

export function parseVeridPrompt(prompt: string): PromptCommand {
  const text = prompt.trim().replace(/^\/verid:/, "/verid ");
  if (!/^\/verid(\s|$)/.test(text)) return { kind: "none" };
  const rest = text.slice("/verid".length).trim();
  const tip = /^tip\s+(.+)$/s.exec(rest);
  if (tip?.[1]) return { kind: "tip", reason: tip[1].trim() };
  const confirm = /^confirm\s+(\S+)$/.exec(rest);
  if (confirm?.[1]) return { kind: "confirm", code: confirm[1] };
  if (rest === "peek" || rest === "menu") return { kind: rest };
  return { kind: "usage" };
}

export interface PromptContext {
  session: string;
  /** Claude Code's own CLAUDE_CODE_SESSION_ATTENDED === "1"; 0 for `claude -p` started by an agent. */
  attended: boolean;
  /** Present when the prompt comes from a subagent. */
  agentId: string | undefined;
  now: string;
  /** Fresh random code, generated by the shell, used only by `tip`. */
  newCode: string;
}

export type PromptOutcome =
  | { kind: "pass" }
  | { kind: "block"; key: ErrorCode | MessageKey; params: Record<string, string> }
  | { kind: "context"; key: MessageKey; params: Record<string, string> };

export interface AuditEvent {
  event: string;
  [field: string]: unknown;
}

export interface PromptResult {
  state: State;
  outcome: PromptOutcome;
  audit: AuditEvent | null;
}

const block = (
  state: State,
  key: ErrorCode | MessageKey,
  params: Record<string, string> = {},
  audit: AuditEvent | null = null,
): PromptResult => ({
  state,
  outcome: { kind: "block", key, params },
  audit,
});

/** The commands that change overrides; peek and menu only read, and the hook shows them. */
export type OverrideCommand = Exclude<PromptCommand, { kind: "peek" | "menu" }>;

export function handlePrompt(state: State, cmd: OverrideCommand, ctx: PromptContext): PromptResult {
  if (cmd.kind === "none") return { state, outcome: { kind: "pass" }, audit: null };
  if (!ctx.attended || ctx.agentId !== undefined)
    return block(
      state,
      "VERID_BURNT_OVERRIDE_UNATTENDED",
      {},
      {
        event: "override_rejected",
        session: ctx.session,
        why: "unattended",
        ...(ctx.agentId !== undefined && { agent_id: ctx.agentId }),
      },
    );
  if (cmd.kind === "usage") return block(state, "VERID_BURNT_OVERRIDE_USAGE");
  return cmd.kind === "tip" ? tip(state, cmd.reason, ctx) : confirm(state, cmd.code, ctx);
}

function tip(state: State, reason: string, ctx: PromptContext): PromptResult {
  const d = state.last_denied;
  if (!d || d.session !== ctx.session) return block(state, "VERID_BURNT_OVERRIDE_NOTHING");
  if (!isOverridable(d.rule))
    return block(state, "VERID_BURNT_OVERRIDE_FORBIDDEN", { rule: d.rule, target: d.target });
  const next: State = {
    ...state,
    pending_override: {
      session: ctx.session,
      code: ctx.newCode,
      reason,
      rule: d.rule,
      tool: d.tool,
      target: d.target,
      input_hash: d.input_hash,
      created_at: ctx.now,
    },
  };
  // The code goes to the developer only: never into the audit log or agent context.
  return block(
    next,
    "override.risk_warning",
    { tool: d.tool, target: d.target, rule: d.rule, reason, code: ctx.newCode },
    {
      event: "override_warned",
      session: ctx.session,
      rule: d.rule,
      tool: d.tool,
      target: d.target,
      reason,
    },
  );
}

function confirm(state: State, code: string, ctx: PromptContext): PromptResult {
  const p = state.pending_override;
  if (!p || p.session !== ctx.session) return block(state, "VERID_BURNT_OVERRIDE_NOTHING");
  if (code.toUpperCase() !== p.code.toUpperCase())
    return block(state, "VERID_BURNT_OVERRIDE_BAD_CODE");
  const d = state.last_denied;
  if (!d || d.input_hash !== p.input_hash || d.rule !== p.rule || d.tool !== p.tool)
    return block({ ...state, pending_override: null }, "VERID_BURNT_OVERRIDE_STALE");
  const created = {
    session: p.session,
    rule: p.rule,
    tool: p.tool,
    target: p.target,
    input_hash: p.input_hash,
    reason: p.reason,
    created_at: ctx.now,
    used: false,
  };
  return {
    state: { ...state, pending_override: null, overrides: [...state.overrides, created] },
    outcome: {
      kind: "context",
      key: "override.created",
      params: { tool: p.tool, target: p.target },
    },
    audit: { event: "override_created", ...created },
  };
}

export function recordDenial(state: State, denied: DeniedAction): State {
  return {
    ...state,
    counters: { ...state.counters, blocked_actions: state.counters.blocked_actions + 1 },
    last_denied: denied,
  };
}

export interface OverrideKey {
  session: string;
  tool: string;
  input_hash: string;
  rule: RuleCode;
}

/** Marks the matching unused override as used; null when none applies. */
export function consumeOverride(state: State, key: OverrideKey, now: string): State | null {
  const i = state.overrides.findIndex(
    (o) =>
      !o.used &&
      o.session === key.session &&
      o.tool === key.tool &&
      o.input_hash === key.input_hash &&
      o.rule === key.rule,
  );
  const found = state.overrides[i];
  if (!found || !isOverridable(key.rule)) return null;
  const overrides = state.overrides.slice();
  overrides[i] = { ...found, used: true, used_at: now };
  return { ...state, overrides };
}
